"""Generate the article figure and table from summary.csv. Requires matplotlib."""

import csv
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'experiment' / 'results'
rows = list(csv.DictReader((RESULTS / 'summary.csv').open()))
lookup = {(row['scenario'], row['strategy']): row for row in rows}
scenarios = [('uniform', 'Равномерная'), ('zipf', 'Zipf'),
             ('shift', 'Смена профиля'), ('heterogeneous', 'Разные узлы')]
labels = {'count': 'Count', 'qps': 'QPS', 'work': 'Work', 'cost': 'Cost'}

figure, axes = plt.subplots(1, 3, figsize=(7.5, 2.15), layout='constrained')
styles = [('qps', '#2563a6', 'o'), ('work', '#8d5c99', 's'), ('cost', '#13795b', '^')]
for axis, (scenario, title) in zip(axes, scenarios[1:]):
    for strategy, color, marker in styles:
        row = lookup[(scenario, strategy)]
        x, y = float(row['migration_mib']), float(row['mean_ms'])
        xerr = [[max(0, x - float(row['migration_mib_low']))],
                [max(0, float(row['migration_mib_high']) - x)]]
        yerr = [[max(0, y - float(row['mean_ms_low']))],
                [max(0, float(row['mean_ms_high']) - y)]]
        axis.errorbar(x, y, xerr=xerr, yerr=yerr, fmt=marker, color=color,
                      markersize=5, capsize=2, linewidth=1, label=labels[strategy])
    axis.set_title(title, fontsize=9)
    axis.set_xlabel('Копирование за серию, МиБ', fontsize=8)
    axis.grid(alpha=0.2)
    axis.tick_params(labelsize=8)
    axis.set_xlim(0, 3500)
axes[0].set_ylabel('Среднее время операции, мс', fontsize=8)
handles, names = axes[0].get_legend_handles_labels()
figure.legend(handles, names, fontsize=8, loc='outside upper center', ncol=3, frameon=False)
(ROOT / 'figures').mkdir(exist_ok=True)
figure.savefig(ROOT / 'figures' / 'tradeoff.png', dpi=300)

lines = [r'% Generated by experiment/make_figure.py. DO NOT EDIT.',
         r'\begin{table*}[t]',
         r'\caption{Результаты синтетического эксперимента: средние по 12 seed}',
         r'\label{tab:results}', r'\centering', r'\small',
         r'\begin{tabular}{llrrrr}', r'\toprule',
         r'Профиль & Стратегия & $\bar\sigma_\rho$ & $\bar R$, мс [95\% ДИ] & $\overline{p95}$, мс & $M$, МиБ \\',
         r'\midrule']
for scenario, label in scenarios:
    for index, strategy in enumerate(['count', 'qps', 'work', 'cost']):
        row = lookup[(scenario, strategy)]
        profile = label if index == 0 else ''
        delay = f"{float(row['mean_ms']):.2f} [{float(row['mean_ms_low']):.2f}; {float(row['mean_ms_high']):.2f}]"
        lines.append(f"{profile} & {labels[strategy]} & {float(row['rho_std']):.3f} & {delay} & "
                     f"{float(row['p95_window_mean_ms']):.2f} & {float(row['migration_mib']):.1f} " + r'\\')
    if scenario != scenarios[-1][0]:
        lines.append(r'\addlinespace[2pt]')
lines.extend([r'\bottomrule', r'\end{tabular}', r'\end{table*}'])
(RESULTS / 'table.tex').write_text('\n'.join(lines) + '\n')
